"""Regenerate the capability table in docs/model-providers.md from the stored provider-check results.

    uv run --project agents/python python -m scripts.build_provider_table           # rewrite the table
    uv run --project agents/python python -m scripts.build_provider_table --check   # fail if it is stale

Inputs are files already in the repo: ``agents/python/evals/provider-results/*.json`` (one per provider and model,
written by ``python -m evals.provider_check --save-result``) and ``not-run.json`` beside them (providers nobody could
run, each with the reason). Nothing is measured here and no model is called, so the output is a pure function of the
committed files and ``--check`` is deterministic. Only the text between the two marker comments in the page is
replaced. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS = REPO_ROOT / "agents" / "python" / "evals" / "provider-results"
NOT_RUN = "not-run.json"
OUTPUT = REPO_ROOT / "docs" / "model-providers.md"
START = "<!-- provider-capabilities:start (generated by scripts/build_provider_table.py; do not edit by hand) -->"
END = "<!-- provider-capabilities:end -->"

# Column order and short headings; the keys are the capability names provider_check writes.
COLUMNS: tuple[tuple[str, str], ...] = (
    ("tool_calling", "Tool calls"),
    ("parallel_tool_calls", "Parallel"),
    ("tool_result", "Tool result"),
    ("tool_choice", "Forced tool"),
    ("streaming_tools", "Streaming"),
    ("json_output", "JSON"),
    ("context_length", "Prompt"),
    ("temperature_param", "Temp."),
    ("embeddings", "Embed."),
)
_CELL = {"pass": "pass", "fail": "FAIL", "unsupported": "n/a"}
_PROVIDER_NAMES = {
    "azure": "Azure OpenAI",
    "openai": "OpenAI-compatible",
    "anthropic": "Anthropic",
}


def load_results(results_dir: Path = RESULTS) -> list[dict[str, Any]]:
    """Every stored check, ordered by provider label then model, so the table is stable."""
    found = [
        json.loads(p.read_text())
        for p in sorted(results_dir.glob("*.json"))
        if p.name != NOT_RUN
    ]
    return sorted(found, key=lambda r: (_provider_label(r), _model_key(r["model"])))


def load_not_run(results_dir: Path = RESULTS) -> list[dict[str, str]]:
    path = results_dir / NOT_RUN
    return json.loads(path.read_text()) if path.exists() else []


def _model_key(model: str) -> list[Any]:
    """Natural order, so gpt-5.4 sorts before gpt-5.10 and the mini variants sort by name."""
    parts: list[Any] = []
    digits = ""
    for ch in model:
        if ch.isdigit():
            digits += ch
            continue
        if digits:
            parts.append((0, int(digits)))
            digits = ""
        parts.append((1, ch))
    if digits:
        parts.append((0, int(digits)))
    return parts


def _provider_label(result: dict[str, Any]) -> str:
    return str(
        result.get("label")
        or _PROVIDER_NAMES.get(result["provider"], result["provider"])
    )


def _token_param(result: dict[str, Any]) -> str:
    details = " ".join(c.get("detail", "") for c in result["capabilities"].values())
    return (
        "max_completion_tokens"
        if "sent max_completion_tokens" in details
        else "max_tokens"
    )


def _tokens(result: dict[str, Any]) -> str:
    total = int(result.get("tokens_in", 0)) + int(result.get("tokens_out", 0))
    return f"{total:,}" if total else "n/a"


def render(results: list[dict[str, Any]], not_run: list[dict[str, str]]) -> str:
    """The generated block, without the marker comments."""
    intro = (
        "Probed by `python -m evals.provider_check`; every row is a stored result with its date, so a model "
        "that is not listed has not been run. `pass` and `FAIL` are the probe's verdict, `n/a` means the "
        "provider has no such API. One probe is one small request: a pass says the wire shape works, not that "
        "the model is good at it."
    )
    lines = [
        intro,
        "",
        "| Provider | Model | Checked | "
        + " | ".join(h for _, h in COLUMNS)
        + " | Token parameter | Tokens used |",
        "|---|---|---|" + "---|" * len(COLUMNS) + "---|---|",
    ]
    for r in results:
        caps = r["capabilities"]
        cells = [
            _CELL.get(caps[key]["status"], "?") if key in caps else "not run"
            for key, _ in COLUMNS
        ]
        row = [
            _provider_label(r),
            f"`{r['model']}`",
            r["date"],
            *cells,
            f"`{_token_param(r)}`",
            _tokens(r),
        ]
        lines.append("| " + " | ".join(row) + " |")

    notes = [
        f"- `{r['model']}` ({_provider_label(r)}), {key.replace('_', ' ')}: {caps[key]['detail']}"
        for r in results
        for caps in [r["capabilities"]]
        for key, _ in COLUMNS
        if key in caps and caps[key]["status"] != "pass"
    ]
    if notes:
        lines += [
            "",
            "What the failing and unavailable probes said, verbatim from the stored results:",
            "",
            *notes,
        ]

    if not_run:
        lines += ["", "Not run:", ""]
        lines += [f"- **{n['provider']}**: not run. {n['reason']}" for n in not_run]
    return "\n".join(lines)


def splice(page: str, block: str) -> str:
    """The page with the text between the markers replaced by ``block``."""
    if START not in page or END not in page or page.index(START) > page.index(END):
        raise ValueError(
            f"{OUTPUT.relative_to(REPO_ROOT)} must contain the two provider-capabilities markers"
        )
    head, _, rest = page.partition(START)
    _, _, tail = rest.partition(END)
    return f"{head}{START}\n\n{block}\n\n{END}{tail}"


def build(output: Path | None = None, results_dir: Path = RESULTS) -> str:
    page = (output or OUTPUT).read_text()
    return splice(page, render(load_results(results_dir), load_not_run(results_dir)))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the table in docs/model-providers.md is stale",
    )
    args = parser.parse_args(argv)
    try:
        text = build()
    except ValueError as exc:
        print(exc)
        return 1
    if args.check:
        if OUTPUT.read_text() != text:
            print(
                "The capability table in docs/model-providers.md is stale; run: "
                "uv run --project agents/python python -m scripts.build_provider_table"
            )
            return 1
        print("docs/model-providers.md capability table is up to date")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
