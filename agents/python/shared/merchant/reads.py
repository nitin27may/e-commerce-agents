"""Read-only access to a seller's proposals and reviews for the merchant-ops agent (#298).

Every function here only SELECTs. The agent never writes: a proposal is generated by
:mod:`shared.merchant.proposals`, decided line by line by the seller through the approvals machinery
(``orchestrator/proposals_service.py``), and this module reads the rows both leave behind.

Scope is decided by :class:`Scope`, built from the caller's identity (ContextVars, never an argument): a
seller sees only their own products, proposals and reviews, an admin sees every seller's. A row that belongs
to someone else is reported exactly like one that does not exist (``None``), so nothing here lets a seller
probe for another seller's ids.
"""

from __future__ import annotations

import json
import uuid
from dataclasses import dataclass
from decimal import Decimal
from typing import Any

import asyncpg

from shared.merchant.review_quality import assess_review, draft_response

Db = asyncpg.Connection | asyncpg.Pool

MAX_EXCERPT = 240
_OPEN_LINE = ("proposed", "accepted", "edited")


@dataclass(frozen=True)
class Scope:
    """Whose data a read may touch: one seller's (``seller_id``) or everyone's (``is_admin``)."""

    email: str
    role: str
    seller_id: uuid.UUID | None

    @property
    def is_admin(self) -> bool:
        return self.role == "admin"

    @property
    def allowed(self) -> bool:
        return self.is_admin or (self.role == "seller" and self.seller_id is not None)


async def scope_for(email: str, role: str, *, db: Db) -> Scope:
    seller_id = None
    if email:
        seller_id = await db.fetchval("SELECT id FROM users WHERE lower(email) = lower($1)", email)
    return Scope(email=email, role=(role or "").lower(), seller_id=seller_id)


def parse_uuid(value: str) -> uuid.UUID | None:
    try:
        return uuid.UUID(str(value).strip())
    except (ValueError, AttributeError):
        return None


def _num(value: Any) -> float | None:
    return None if value is None else round(float(value), 2)


def _json(value: Any) -> dict[str, Any]:
    if isinstance(value, str):
        return json.loads(value)
    return dict(value) if value else {}


# ── proposals ────────────────────────────────────────────────────────────────


def describe_line(row: asyncpg.Record) -> dict[str, Any]:
    """One proposal line with the effect worked out from the facts stored on the row, never invented."""
    evidence = _json(row["evidence"])
    guard = _json(row["guard_result"]) if row["guard_result"] else {}
    current, proposed = row["current_value"], row["proposed_value"]
    cost = row["unit_cost"]
    window = int(evidence.get("window_days") or 90)
    sold = evidence.get("units_sold")
    line: dict[str, Any] = {
        "line_id": str(row["id"]),
        "product_id": str(row["product_id"]),
        "product_name": row["product_name"],
        "field": row["field"],
        "status": row["status"],
        "rationale": row["rationale"],
        "guard_ok": bool(guard.get("ok", True)),
        "blocked_reasons": list(guard.get("reasons", [])),
        "stock": evidence.get("stock"),
        "units_sold_window": sold,
        "window_days": window,
        "units_sold_per_day": None if sold is None else round(sold / window, 2),
    }
    if row["field"] == "price":
        drop = None if current is None else current - proposed
        line.update(
            current_price=_num(current),
            proposed_price=_num(proposed),
            unit_price_drop=_num(drop),
            change_pct=None if not current else round(float(drop / current * 100), 1),
            cover_days=None if evidence.get("cover_days") in (None, "") else round(float(evidence["cover_days"]), 1),
            stock_value_at_current_price=(
                None if current is None or evidence.get("stock") is None else _num(current * evidence["stock"])
            ),
            margin_pct_at_proposed=(
                None if cost is None or not proposed else round(float((proposed - cost) / proposed * 100), 1)
            ),
        )
    else:
        quantity = int(proposed)
        line.update(
            units_to_order=quantity,
            order_value=None if cost is None else _num(cost * Decimal(quantity)),
            short_warehouses=evidence.get("short_warehouses", []),
        )
    return line


def rank_lines(lines: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Order open lines by what to approve first and say why; blocked and decided lines are not ranked.

    Restocks come first (a stock-out loses sales that no price change recovers), the larger order first.
    Markdowns follow, deepest overstock first (no sales at all is the deepest). Every tie breaks on the
    product name and line id, so the order is the same on every call. The returned list is the input lines
    plus ``approve_order`` (1-based, ``None`` when not ranked) and ``approve_reason``.
    """
    open_lines = [ln for ln in lines if ln["status"] in _OPEN_LINE and ln["guard_ok"]]
    restocks = sorted(
        (ln for ln in open_lines if ln["field"] == "restock_quantity"),
        key=lambda ln: (-ln["units_to_order"], ln["product_name"], ln["line_id"]),
    )
    markdowns = sorted(
        (ln for ln in open_lines if ln["field"] == "price"),
        key=lambda ln: (-(10**9 if ln["cover_days"] is None else ln["cover_days"]), ln["product_name"], ln["line_id"]),
    )
    order: dict[str, tuple[int, str]] = {}
    for line in restocks:
        short = len(line["short_warehouses"])
        order[line["line_id"]] = (
            len(order) + 1,
            f"restock first: {short} warehouse(s) are below their reorder threshold, so sales are at risk",
        )
    for line in markdowns:
        cover = line["cover_days"]
        why = (
            "no sales in the window, the deepest overstock"
            if cover is None
            else f"about {cover} days of cover at the recent sales rate"
        )
        order[line["line_id"]] = (len(order) + 1, f"markdown: {why}")
    ranked = []
    for line in lines:
        position, reason = order.get(line["line_id"], (None, None))
        if position is None:
            if not line["guard_ok"]:
                reason = "blocked by a merchant guard and can only be rejected: " + ", ".join(line["blocked_reasons"])
            else:
                reason = f"already {line['status']}"
        ranked.append({**line, "approve_order": position, "approve_reason": reason})
    # Unranked lines (blocked or decided) keep a stable order by name, then field: never a random line id.
    return sorted(
        ranked,
        key=lambda ln: (
            ln["approve_order"] is None,
            ln["approve_order"] or 0,
            ln["product_name"],
            ln["field"],
            ln["line_id"],
        ),
    )


_LINES_SQL = """SELECT l.*, p.name AS product_name, p.unit_cost
                  FROM proposal_lines l JOIN products p ON p.id = l.product_id
                 WHERE l.proposal_id = ANY($1::uuid[])
                 ORDER BY l.created_at, p.name, l.field, l.id"""


async def list_proposals(scope: Scope, *, db: Db, status: str | None = None, limit: int = 5) -> list[dict[str, Any]]:
    """The scope's proposals, newest first, with a one-line summary each (lines come from :func:`get_proposal`)."""
    rows = await db.fetch(
        """SELECT pr.id, pr.kind, pr.status, pr.created_at, u.email AS seller_email, a.status AS approval_status,
                  (SELECT count(*) FROM proposal_lines l WHERE l.proposal_id = pr.id) AS line_count,
                  (SELECT count(*) FROM proposal_lines l WHERE l.proposal_id = pr.id AND l.status = 'blocked')
                      AS blocked_count
             FROM proposals pr
             JOIN users u ON u.id = pr.seller_id
             LEFT JOIN approvals a ON a.source = 'proposal' AND a.source_ref = pr.id
            WHERE ($1::uuid IS NULL OR pr.seller_id = $1)
              AND ($2::text IS NULL OR pr.status = $2)
            ORDER BY pr.created_at DESC, pr.id
            LIMIT $3""",
        None if scope.is_admin else scope.seller_id,
        status,
        max(1, min(int(limit), 20)),
    )
    return [
        {
            "proposal_id": str(r["id"]),
            "seller_email": r["seller_email"],
            "kind": r["kind"],
            "status": r["status"],
            "approval_status": r["approval_status"],
            "created_at": r["created_at"].isoformat(),
            "lines": r["line_count"],
            "blocked_lines": r["blocked_count"],
        }
        for r in rows
    ]


async def newest_open_proposal_id(scope: Scope, *, db: Db) -> uuid.UUID | None:
    """The newest ``pending_review`` batch in scope (an admin's scope is every seller's), or ``None``."""
    return await db.fetchval(
        """SELECT id FROM proposals
            WHERE status = 'pending_review' AND ($1::uuid IS NULL OR seller_id = $1)
            ORDER BY created_at DESC, id LIMIT 1""",
        None if scope.is_admin else scope.seller_id,
    )


async def get_proposal(scope: Scope, proposal_id: uuid.UUID, *, db: Db) -> dict[str, Any] | None:
    """One proposal with every line explained and ranked; ``None`` if absent or not the scope's."""
    row = await db.fetchrow(
        """SELECT pr.id, pr.kind, pr.status, pr.created_at, pr.seller_id, u.email AS seller_email
             FROM proposals pr JOIN users u ON u.id = pr.seller_id WHERE pr.id = $1""",
        proposal_id,
    )
    if row is None or not (scope.is_admin or row["seller_id"] == scope.seller_id):
        return None
    lines = [describe_line(r) for r in await db.fetch(_LINES_SQL, [proposal_id])]
    ranked = rank_lines(lines)
    return {
        "proposal_id": str(row["id"]),
        "seller_email": row["seller_email"],
        "kind": row["kind"],
        "status": row["status"],
        "created_at": row["created_at"].isoformat(),
        "lines": ranked,
        "open_lines": sum(1 for ln in ranked if ln["approve_order"] is not None),
        "blocked_lines": sum(1 for ln in ranked if not ln["guard_ok"]),
        "decide_at": "/seller/proposals",
    }


# ── reviews ──────────────────────────────────────────────────────────────────

_REVIEW_COLUMNS = """r.id, r.product_id, r.rating, r.title, r.body, r.verified_purchase, r.helpful_count, r.is_flagged,
                     r.created_at, p.name AS product_name, u.name AS reviewer_name"""


def describe_review(row: asyncpg.Record) -> dict[str, Any]:
    quality = assess_review(
        rating=row["rating"], title=row["title"], body=row["body"], product_name=row["product_name"]
    )
    body = row["body"] or ""
    return {
        "review_id": str(row["id"]),
        "product_id": str(row["product_id"]),
        "product_name": row["product_name"],
        "rating": row["rating"],
        "title": row["title"],
        "body_excerpt": body[:MAX_EXCERPT] + ("..." if len(body) > MAX_EXCERPT else ""),
        "verified_purchase": bool(row["verified_purchase"]),
        "platform_flagged": bool(row["is_flagged"]),
        "created_at": row["created_at"].isoformat(),
        **quality.to_dict(),
    }


async def product_in_scope(scope: Scope, product_id: uuid.UUID, *, db: Db) -> asyncpg.Record | None:
    return await db.fetchrow(
        "SELECT id, name FROM products WHERE id = $1 AND ($2::uuid IS NULL OR seller_id = $2)",
        product_id,
        None if scope.is_admin else scope.seller_id,
    )


async def triage_reviews(
    scope: Scope, *, db: Db, product_id: uuid.UUID | None = None, limit: int = 20, only_attention: bool = False
) -> dict[str, Any] | None:
    """Recent reviews of the scope's products with quality signals; ``None`` when ``product_id`` is not in scope."""
    if product_id is not None and await product_in_scope(scope, product_id, db=db) is None:
        return None
    rows = await db.fetch(
        f"""SELECT {_REVIEW_COLUMNS}
              FROM reviews r
              JOIN products p ON p.id = r.product_id
              JOIN users u ON u.id = r.user_id
             WHERE ($1::uuid IS NULL OR p.seller_id = $1)
               AND ($2::uuid IS NULL OR r.product_id = $2)
             ORDER BY r.created_at DESC, r.id
             LIMIT $3""",  # noqa: S608 - the column list is a module constant
        None if scope.is_admin else scope.seller_id,
        product_id,
        max(1, min(int(limit), 50)),
    )
    reviews = [describe_review(r) for r in rows]
    if only_attention:
        reviews = [r for r in reviews if r["suggested_action"] != "none"]
    counts: dict[str, int] = {}
    for review in reviews:
        counts[review["suggested_action"]] = counts.get(review["suggested_action"], 0) + 1
    return {"reviews": reviews, "count": len(reviews), "by_suggested_action": counts}


async def draft_for_review(scope: Scope, review_id: uuid.UUID, *, db: Db) -> dict[str, Any] | None:
    """A review's assessment and, when advised, a draft reply; ``None`` if absent or not the scope's."""
    row = await db.fetchrow(
        f"""SELECT {_REVIEW_COLUMNS}, p.seller_id
              FROM reviews r
              JOIN products p ON p.id = r.product_id
              JOIN users u ON u.id = r.user_id
             WHERE r.id = $1""",  # noqa: S608 - the column list is a module constant
        review_id,
    )
    if row is None or not (scope.is_admin or row["seller_id"] == scope.seller_id):
        return None
    quality = assess_review(
        rating=row["rating"], title=row["title"], body=row["body"], product_name=row["product_name"]
    )
    draft = draft_response(
        rating=row["rating"], product_name=row["product_name"], reviewer=row["reviewer_name"], quality=quality
    )
    return {
        **describe_review(row),
        "draft_response": draft,
        "draft_note": (
            "A draft only: nothing was sent or posted. The seller edits and sends it themselves."
            if draft
            else "No reply is advised for this review."
        ),
    }
